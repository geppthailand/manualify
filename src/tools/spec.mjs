/**
 * Demo → build spec. In demo-driven development the approved demo IS the contract:
 * its captions are the story, its targets are the elements the real app must expose,
 * its expectations are the acceptance criteria, and the same .mul replays against the
 * real app (`manualify test demo.mul --base <url>`) to prove it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { parse, walk, showTarget } from '../mul/parse.mjs';

const slug = (s) => String(s).toLowerCase().normalize('NFKD').replace(/[̀-ͯ]/g, '').replace(/[^\w]+/g, '-').replace(/^-|-$/g, '').slice(0, 40);

function testidFor(t) {
  if (!t) return null;
  if (t.kind === 'id') return t.value;
  if (t.kind === 'macro' && t.value) return `${slug(t.value)}-${t.name}`;
  if (t.kind === 'text') return slug(t.value);
  return null;
}

export function specFromDemo(dir) {
  const mulFile = path.join(dir, 'demo.mul');
  const doc = parse(fs.readFileSync(mulFile, 'utf8'), { file: mulFile });
  const brief = fs.existsSync(path.join(dir, 'brief.md')) ? fs.readFileSync(path.join(dir, 'brief.md'), 'utf8') : '';
  const screensSrc = fs.existsSync(path.join(dir, 'proto', 'screens.js')) ? fs.readFileSync(path.join(dir, 'proto', 'screens.js'), 'utf8') : '';
  const block = (name) => { const i = screensSrc.indexOf(`window.${name}`); if (i < 0) return ''; const j = screensSrc.indexOf('\nwindow.', i + 1); return screensSrc.slice(i, j < 0 ? undefined : j); };
  const screens = [...block('SCREENS').matchAll(/^\s+['"]?([\w-]+)['"]?\s*:\s*\(/gm)].map((m) => m[1]);
  const actions = [...block('ACTIONS').matchAll(/^\s+['"]?([\w-]+)['"]?\s*(?::\s*(?:function\s*)?)?\(\s*state/gm)].map((m) => m[1]);

  const story = [];
  const elements = new Map();
  const steps = [];
  let section = null;
  walk(doc.steps, (n) => {
    if (n.verb === 'section') { section = n.text; steps.push(`\n**${n.text}**`); return; }
    if (n.verb === 'say') { story.push(n.text.replace(/\*\*/g, '')); return; }
    const targets = [n.target, ...(n.targets || []), ...(n.opts?.to || [])].filter(Boolean);
    for (const t of targets) {
      const k = showTarget(t);
      if (!elements.has(k)) elements.set(k, { target: k, testid: testidFor(t), first: section, verbs: new Set() });
      elements.get(k).verbs.add(n.verb);
    }
    if (['click', 'type', 'pick', 'drag', 'key', 'go', 'hover'].includes(n.verb) || n.expects?.length) {
      const what = n.verb === 'go' ? `open \`${n.text}\`` : n.verb === 'type' ? `type "${n.value}" into ${showTarget(n.target)}` : n.verb === 'pick' ? `choose "${n.value}" in ${showTarget(n.target)}` :
        n.verb === 'drag' ? `drag ${showTarget(n.target)} ${n.opts.to ? 'to ' + showTarget(n.opts.to) : `by ${n.opts.by.dx},${n.opts.by.dy}`}` : n.verb === 'expect' ? 'check' : `${n.verb} ${showTarget(n.target)}`;
      const acc = (n.expects || []).map((e) => (e.page ? `${e.page} ${e.op || ''} ${e.value || ''}`.trim() : `${showTarget(e.target)} ${e.preds.map((p) => p.name + (p.op ? p.op + p.value : '')).join(' ')}`));
      steps.push(`- [ ] ${what}${acc.length ? ` → **then** ${acc.join('; ')}` : ''}  _(demo.mul:${n.line})_`);
    }
  });

  const out = [
    `# Build spec — ${doc.meta.title || path.basename(dir)}`,
    '',
    `Generated by \`manualify spec\` from \`demo.mul\`. The approved demo video is the contract; this file lists what the real`,
    `implementation must provide so that the **same script** passes against it:`,
    '',
    '```sh',
    `npx manualify test ${path.relative(process.cwd(), mulFile)} --base http://localhost:<real-app-port>`,
    '```',
    '',
    brief ? `## Brief\n\n${brief.replace(/^#.*\n/, '').trim()}\n` : '',
    '## Story (what the viewer is told, in order)',
    '',
    ...story.map((s, i) => `${i + 1}. ${s}`),
    '',
    screens.length ? `## Screens in the prototype\n\n${screens.map((s) => `- \`${s}\``).join('\n')}\n` : '',
    actions.length ? `## Behaviours the prototype fakes\n\n${actions.map((a) => `- \`${a}\``).join('\n')}\n` : '',
    '## Elements the demo touches',
    '',
    '| Target in demo.mul | Used for | Suggested `data-testid` |',
    '|---|---|---|',
    ...[...elements.values()].map((e) => `| \`${e.target}\` | ${[...e.verbs].join(', ')} | ${e.testid ? `\`${e.testid}\`` : '—'} |`),
    '',
    'Giving these elements the suggested `data-testid` and switching the script to `#testid` targets makes the',
    'acceptance test immune to copy changes.',
    '',
    '## Interactions & acceptance criteria',
    ...steps,
    '',
    '## Out of scope',
    '',
    'Anything the demo does not show. The prototype fakes data and side effects; the real app decides persistence,',
    'validation messages, permissions and error states — add `expect` lines to demo.mul for any of them that matter.',
    '',
  ].join('\n');
  const file = path.join(dir, 'spec.md');
  fs.writeFileSync(file, out.replace(/\n{3,}/g, '\n\n'));
  return file;
}
